function isException(file: string, rule: RuleId): boolean {
  return EXCEPTIONS.some(
    (exception) =>
      exception.rules.includes(rule) &&
      (exception.path.endsWith("/") ? file.startsWith(exception.path) : file === exception.path),
  );
}

function maskCssComments(text: string): string {
  return text.replace(/\/\*[\s\S]*?\*\//g, (comment) => comment.replace(/[^\n]/g, " "));
}

function stringMask(text: string, file: string): Uint8Array {
  const kind = file.endsWith(".tsx")
    ? ts.ScriptKind.TSX
    : file.endsWith(".ts")
      ? ts.ScriptKind.TS
      : ts.ScriptKind.JS;
  const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, false, kind);
  const mask = new Uint8Array(text.length);
  const visit = (node: ts.Node): void => {
    if (ts.isStringLiteralLike(node) || ts.isTemplateLiteralToken(node) || ts.isJsxText(node)) {
      mask.fill(1, node.getStart(source), node.end);
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  return mask;
}

function lineStarts(text: string): number[] {
  const starts = [0];
  for (let index = text.indexOf("\n"); index !== -1; index = text.indexOf("\n", index + 1)) {
    starts.push(index + 1);
  }
  return starts;
}

function locate(starts: number[], index: number): { line: number; column: number } {
  let low = 0;
  let high = starts.length - 1;
  while (low < high) {
    const middle = (low + high + 1) >> 1;
    if (starts[middle]! <= index) low = middle;
    else high = middle - 1;
  }
  return { line: low + 1, column: index - starts[low]! + 1 };
}

export function lintText(text: string, file: string): Violation[] {
  const isCss = file.endsWith(".css");
  const code = isCss ? maskCssComments(text) : text;
  const strings = isCss ? null : stringMask(code, file);
  const starts = lineStarts(text);
  const found = new Map<string, Hit & { rule: RuleId }>();

  for (const check of CHECKS) {
    if (isException(file, check.rule)) continue;
    const subject = check.rule === "emoji" ? text : code;
    for (const hit of check.find(subject)) {
      if (check.scope === "strings" && strings && !strings[hit.index]) continue;
      found.set(`${check.rule}:${hit.index}`, { ...hit, rule: check.rule });
    }
  }

  return [...found.values()]
    .sort((a, b) => a.index - b.index)
    .map(({ rule, index, text: matched }) => ({ rule, ...locate(starts, index), text: matched }));
}

async function listFiles(directory: string): Promise<string[]> {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries
      .filter((entry) => !(entry.isDirectory() && IGNORED_DIRECTORIES.has(entry.name)))
      .map(async (entry) => {
        const full = path.join(directory, entry.name);
        if (entry.isDirectory()) return listFiles(full);
        return EXTENSIONS.has(path.extname(entry.name)) ? [full] : [];
      }),
  );
  return nested.flat().sort();
}

async function main(): Promise<number> {
  const root = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
  const files = (await Promise.all(ROOTS.map((entry) => listFiles(path.join(root, entry))))).flat();

  let total = 0;
  let affected = 0;
  for (const full of files) {
    const file = path.relative(root, full).split(path.sep).join("/");
    const violations = lintText(await readFile(full, "utf8"), file);
    if (violations.length > 0) affected += 1;
    for (const { rule, line, column, text } of violations) {
      console.error(
        `${file}:${line}:${column}  ${rule}  ${JSON.stringify(text)}  ${MESSAGES[rule]}`,
      );
    }
    total += violations.length;
  }

  if (total > 0) {
    console.error(`design-lint: ${total} violation(s) in ${affected} file(s).`);
    return 1;
  }
  console.log(`design-lint: ${files.length} files checked, no violation.`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().then(
    (code) => process.exit(code),
    (error: unknown) => {
      console.error(error);
      process.exit(2);
    },
  );
}
