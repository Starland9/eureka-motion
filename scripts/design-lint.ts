interface Hit {
  index: number;
  text: string;
}

interface Check {
  rule: RuleId;
  scope: "strings" | "all";
  find: (text: string) => Hit[];
}

function pattern(source: string, flags = ""): RegExp {
  return new RegExp(source, `g${flags}`);
}

function finder(regex: RegExp, skip?: (match: RegExpExecArray) => boolean) {
  return (text: string): Hit[] => {
    const hits: Hit[] = [];
    for (const match of text.matchAll(regex)) {
      if (!skip?.(match)) hits.push({ index: match.index, text: match[0] });
    }
    return hits;
  };
}

function property(names: string, reset: RegExp) {
  const value = String.raw`(?:["']?\s*[:=]\s*["'\`]?(?<value>[^;,}\n\]"'\`]*))?`;
  return finder(pattern(String.raw`(?<![\w$.-])(?:${names})${value}`), (match) =>
    reset.test(match.groups?.value ?? "\0"),
  );
}

function namedColor(text: string): Hit[] {
  const key = String.raw`(?:(?:[a-z]+-)*color|[a-zA-Z]*Color|background|border(?:-(?:top|right|bottom|left))?|border(?:Top|Right|Bottom|Left)?|outline|fill|stroke)`;
  const declaration = pattern(
    String.raw`(?<![\w$.-])${key}["']?\s*[:=]\s*\{?\s*["'\`]?([^;,}\n\]"'\`]*)`,
    "d",
  );
  const name = pattern(String.raw`(?<![\w$#.-])(?:${CSS_COLOR_NAMES})(?![\w.(-])`, "i");
  const hits: Hit[] = [];
  for (const match of text.matchAll(declaration)) {
    const start = match.indices?.[1]?.[0] ?? match.index;
    for (const color of match[1]!.matchAll(name)) {
      hits.push({ index: start + color.index, text: color[0] });
    }
  }
  return hits;
}

