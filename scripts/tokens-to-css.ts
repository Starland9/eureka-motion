import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  breakpointsPx,
  colorCssVariables,
  fontCssVariables,
  fontStacks,
  grid,
  ICON_STROKE_PX,
  LEAVE_DURATION_RATIO,
  REDUCED_MOTION_FADE_MS,
  staticCssVariables,
  TOUCH_TARGET_PX,
  typeScale,
  type FontRole,
  type TypeStyle,
} from "scene";

const OUTPUT = fileURLToPath(new URL("../apps/web/src/app/tokens.css", import.meta.url));

const BREAKPOINT_NAMES = ["xs", "sm", "md", "lg", "xl", "2xl"] as const;

type Declarations = Record<string, string>;

function kebab(name: string): string {
  return name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

function px(value: number | string): string {
  return typeof value === "number" ? `${value}px` : value;
}

function block(selector: string, declarations: Declarations): string {
  const lines = Object.entries(declarations).map(
    ([name, value]) => `  ${name}: ${value.replace(/^#[0-9A-F]{6}$/, (hex) => hex.toLowerCase())};`,
  );
  return `${selector} {\n${lines.join("\n")}\n}`;
}

function fontVariables(): Declarations {
  const declarations: Declarations = {};
  for (const role of Object.keys(fontStacks) as FontRole[]) {
    declarations[fontCssVariables[role]] = fontStacks[role];
  }
  return declarations;
}

function typeVariables(): Declarations {
  const declarations: Declarations = {};
  for (const [name, style] of Object.entries(typeScale) as [string, TypeStyle][]) {
    const prefix = `--type-${kebab(name)}`;
    declarations[`${prefix}-font`] = `var(${fontCssVariables[style.font]})`;
    declarations[`${prefix}-size`] = px(style.size);
    declarations[`${prefix}-leading`] = String(style.lineHeight);
    declarations[`${prefix}-weight`] = String(style.weight);
    if (style.tracking !== undefined) declarations[`${prefix}-tracking`] = `${style.tracking}em`;
  }
  return declarations;
}

function layoutVariables(): Declarations {
  return {
    "--touch-target": `${TOUCH_TARGET_PX}px`,
    "--icon-stroke": String(ICON_STROKE_PX),
    "--duration-reduced": `${REDUCED_MOTION_FADE_MS}ms`,
    "--leave-ratio": String(LEAVE_DURATION_RATIO),
    "--gutter": `${grid.gutterPx}px`,
    "--margin-phone": `${grid.marginPx.phone}px`,
    "--margin-tablet": `${grid.marginPx.tablet}px`,
    "--margin-desktop": `${grid.marginPx.desktop}px`,
    "--content-max": `${grid.maxContentWidthPx}px`,
  };
}

function breakpointVariables(): Declarations {
  const declarations: Declarations = {};
  breakpointsPx.forEach((width, index) => {
    declarations[`--breakpoint-${BREAKPOINT_NAMES[index]}`] = `${width}px`;
  });
  return declarations;
}

const css = [
  "/* Generated by scripts/tokens-to-css.ts from packages/scene/src/tokens. Do not edit. */",
  block(":root", {
    ...colorCssVariables("paper"),
    ...staticCssVariables(),
    ...layoutVariables(),
    ...fontVariables(),
    ...typeVariables(),
  }),
  block(".dark", colorCssVariables("board")),
  block("@theme", breakpointVariables()),
]
  .join("\n\n")
  .concat("\n");

writeFileSync(OUTPUT, css);
